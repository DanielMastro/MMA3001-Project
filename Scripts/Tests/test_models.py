"""
test_models.py - checks for models.py.

  * every model has the same methods and returns the right shapes
  * polynomial_regression fits polynomial data exactly
  * constant_inductance recovers psi_pm, Ld and Lq of a linear motor
  * lookup_table passes exactly through its training points
  * neural_network's chain-rule gradient matches finite differences
  * points outside the FEA range are flagged as extrapolation
"""

import numpy as np
import pytest

import derive as dv
import models as md
from conftest import known_flux


def cobalt_like_grid():
    """A Cobalt-like FEA sweep: 0-113 A in 11 rings x 0-90 deg in 15 deg steps."""
    I, beta = np.meshgrid(np.linspace(11.33, 113.3, 10), np.deg2rad(np.arange(0, 91, 15)))
    Id = np.r_[0.0, (-I * np.sin(beta)).ravel()]
    Iq = np.r_[0.0, (I * np.cos(beta)).ravel()]
    return Id, Iq


ALL_MODELS = [md.constant_inductance, md.lookup_table,
              lambda: md.polynomial_regression(3), lambda: md.neural_network(8)]


@pytest.mark.parametrize("make_model", ALL_MODELS)
def test_common_interface(make_model):
    """Every model: fit, predict_flux, flux_gradient, is_extrapolation, n_parameters."""
    Id, Iq = cobalt_like_grid()
    model = make_model().fit(Id, Iq, *known_flux(Id, Iq))
    q_d, q_q = np.array([[-10.0, -20.0]]), np.array([[50.0, 60.0]])        # a 1x2 query
    psi_d, psi_q = model.predict_flux(q_d, q_q)
    assert psi_d.shape == psi_q.shape == (1, 2)
    g = model.flux_gradient(q_d, q_q)
    assert set(g) == {"dpsid_did", "dpsid_diq", "dpsiq_did", "dpsiq_diq"}
    assert g["dpsid_did"].shape == (1, 2)
    assert model.n_parameters > 0 and model.flops_per_eval() > 0
    assert model.is_extrapolation(q_d, q_q).shape == (1, 2)


def test_polynomial_fits_polynomial_exactly():
    """Data generated by a cubic is reproduced exactly by a cubic fit, off the grid too."""
    Id, Iq = cobalt_like_grid()
    f = lambda a, b: (0.05 + 1e-4 * a - 2e-6 * a * b + 3e-9 * b**3,
                      7e-4 * b + 1e-6 * a**2 - 4e-9 * a * b**2)
    model = md.polynomial_regression(3).fit(Id, Iq, *f(Id, Iq))
    Id_t, Iq_t = np.array([-33.0, -71.0]), np.array([47.0, 9.0])
    np.testing.assert_allclose(model.predict_flux(Id_t, Iq_t), f(Id_t, Iq_t), rtol=1e-9)


def test_constant_inductance_recovers_linear_motor():
    Id, Iq = cobalt_like_grid()
    model = md.constant_inductance().fit(Id, Iq, 0.048 + 500e-6 * Id, 600e-6 * Iq)
    v = model.fitted_values()
    np.testing.assert_allclose([v["psi_pm"], v["Ld"], v["Lq"]], [0.048, 500e-6, 600e-6], rtol=1e-10)


def test_lookup_passes_through_training_points():
    Id, Iq = cobalt_like_grid()
    psi_d, psi_q = known_flux(Id, Iq)
    model = md.lookup_table().fit(Id, Iq, psi_d, psi_q)
    p_d, p_q = model.predict_flux(Id, Iq)
    np.testing.assert_allclose(p_d, psi_d, atol=1e-12)
    np.testing.assert_allclose(p_q, psi_q, atol=1e-12)


def test_neural_network_gradient_matches_finite_difference():
    """Checks the chain-rule gradient code against a 5-point stencil on the
    same network's predictions."""
    Id, Iq = cobalt_like_grid()
    model = md.neural_network(8).fit(Id, Iq, *known_flux(Id, Iq))
    Id_t, Iq_t = np.array([-20.0, -60.0, -90.0]), np.array([90.0, 50.0, 20.0])
    exact = dv.incremental_inductance(model, Id_t, Iq_t, method="analytic")
    fd = dv.incremental_inductance(model, Id_t, Iq_t, method="fd5", h=0.05)
    for key in exact:
        np.testing.assert_allclose(exact[key], fd[key], rtol=1e-5, atol=1e-9, err_msg=key)


def test_extrapolation_flag():
    """Inside the 0-113 A, 0-90 deg sweep -> False; larger current or another
    quadrant -> True."""
    Id, Iq = cobalt_like_grid()
    model = md.polynomial_regression(3).fit(Id, Iq, *known_flux(Id, Iq))
    flags = model.is_extrapolation(np.array([0.0, -50.0, 0.0, 10.0, -50.0]),
                                   np.array([50.0, 0.0, 200.0, 50.0, -10.0]))
    assert flags.tolist() == [False, False, True, True, True]
